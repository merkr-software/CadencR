import { formattingLocale } from "@/lib/i18n/formatting-locale";
import { formatExactNumber } from "@/lib/format-number";
import { useUiTranslation, type UiTranslator } from "@/lib/i18n/ui";
import { useMemo, useState } from "react";
import { keepPreviousData } from "@tanstack/react-query";
import { useGetUsageStats } from "@/api/generated";
import { apiErrorMessage } from "@/lib/api-errors";
import { Skeleton } from "@/components/ui/skeleton";
import { SettingsPageSection } from "./SettingsPageSection";
import { SettingsGroup } from "@/components/settings/SettingsGroup";
import { SettingsSubsection } from "@/components/settings/SettingsSubsection";
import { WARNING_BANNER_CLASS } from "@/components/settings/SettingsWarningsBanner";
import {
  UsageSegmentedControl,
  type SegmentedOption,
} from "@/components/usage/UsageSegmentedControl";
import { UsageSummaryTiles } from "@/components/settings/stats/UsageSummaryTiles";
import { UsageOverviewChart } from "@/components/usage/UsageOverviewChart";
import { UsagePlotSkeleton } from "@/components/usage/UsagePlotPlaceholder";
import { useUsageCharts } from "@/components/usage/use-usage-charts";
import {
  resolveEndDay,
  type UsageGrouping,
  type UsageMetric,
  type UsageScale,
} from "@/components/usage/usage-stats-model";
import { UsageRecordingWarning } from "@/components/settings/stats/UsageRecordingWarning";
import { emptyUsageRange } from "@/components/usage/usage-copy";
import { cn } from "@/lib/utils";

const RANGE_VALUES = ["7", "30", "90"] as const;

function usageOptions(t: UiTranslator, locale: string) {
  return {
    ranges: RANGE_VALUES.map((value) => {
      const days = formatExactNumber(Number(value), locale);
      return {
        value,
        label: t("system.usage.shortDays", "{{days}}d", { days }),
        title: t("system.usage.lastDays", "Last {{days}} days", { days }),
      };
    }),
    metrics: [
      {
        value: "total",
        label: t("system.usage.total", "Total"),
        title: t("system.usage.totalMeasure", "Input plus output tokens"),
      },
      {
        value: "input",
        label: t("system.usage.input", "Input"),
        title: t("system.usage.inputMeasure", "Input tokens processed by the provider"),
      },
      {
        value: "output",
        label: t("system.usage.output", "Output"),
        title: t("system.usage.outputMeasure", "Output tokens generated by the provider"),
      },
      {
        value: "messages",
        label: t("system.usage.messages", "Messages"),
        title: t("system.usage.messageMeasure", "Prompts you sent, by the model they went to"),
      },
    ] as const satisfies readonly SegmentedOption<UsageMetric>[],
    grouping: [
      {
        value: "provider",
        label: t("system.usage.provider", "Provider"),
        title: t("system.usage.providerGrouping", "One series per provider"),
      },
      {
        value: "model",
        label: t("system.usage.model", "Model"),
        title: t("system.usage.modelGrouping", "One series per provider and model"),
      },
    ] as const satisfies readonly SegmentedOption<UsageGrouping>[],
    scales: [
      {
        value: "absolute",
        label: t("system.usage.absolute", "Absolute"),
        title: t("system.usage.absoluteScale", "Each day against the busiest day"),
      },
      {
        value: "share",
        label: t("system.usage.share", "Share"),
        title: t("system.usage.shareScale", "Each day as its own mix, filled to the top"),
      },
    ] as const satisfies readonly SegmentedOption<UsageScale>[],
  };
}

export function StatsSection(): React.JSX.Element {
  const { t, i18n } = useUiTranslation();
  const [range, setRange] = useState<(typeof RANGE_VALUES)[number]>("30");
  const [metric, setMetric] = useState<UsageMetric>("total");
  const [grouping, setGrouping] = useState<UsageGrouping>("provider");
  const [scale, setScale] = useState<UsageScale>("absolute");
  const locale = formattingLocale(i18n.language);
  const options = useMemo(() => usageOptions(t, locale), [t, locale]);

  // The last range stays on screen while the next one loads, so switching
  // ranges never flashes a skeleton.
  const { data, isLoading, error } = useGetUsageStats(
    { days: Number(range) },
    { query: { placeholderData: keepPreviousData } },
  );
  // The window of the data on screen, which lags the selection until it lands.
  const windowDays = data?.days ?? Number(range);
  const entries = useMemo(() => data?.entries ?? [], [data?.entries]);
  // The backend computes the window's last day from the same clock that stamped
  // the rows; deriving it here would drift across UTC midnight.
  const endDay = resolveEndDay(data?.end_day);
  const { chart, labelOf, summary } = useUsageCharts({
    entries,
    windowDays,
    endDay,
    metric,
    grouping,
  });

  return (
    <SettingsPageSection pageId="stats">
      <SettingsGroup
        title={t("system.statsSection.overview", "Overview")}
        description={t(
          "system.statsSection.tokensComeFromEachProviderSOwnUsage",
          "Tokens come from each provider's own usage events; messages are counted as you send them.",
        )}
      >
        <SettingsSubsection>
          {/* One row of options for the whole overview: the tiles and the chart
              below answer to the same range, measure, grouping and scale. */}
          <div className="mb-5 flex flex-wrap items-center gap-2">
            <UsageSegmentedControl
              value={range}
              options={options.ranges}
              onChange={setRange}
              ariaLabel={t("system.usage.timeRange", "Time range")}
            />
            <UsageSegmentedControl
              value={metric}
              options={options.metrics}
              onChange={setMetric}
              ariaLabel={t("system.usage.measure", "Measure")}
            />
            <UsageSegmentedControl
              value={grouping}
              options={options.grouping}
              onChange={setGrouping}
              ariaLabel={t("system.usage.groupBy", "Group by")}
            />
            <UsageSegmentedControl
              value={scale}
              options={options.scales}
              onChange={setScale}
              ariaLabel={t("system.usage.scale", "Scale")}
            />
          </div>
          {/* Outside `StatsBody` on purpose: a failed write is often the reason
              there is nothing to chart, so it must survive the empty state. */}
          {data?.recording_issue ? (
            <div className="mb-4">
              <UsageRecordingWarning issue={data.recording_issue} />
            </div>
          ) : null}
          <StatsBody
            windowDays={windowDays}
            isLoading={isLoading}
            error={error}
            hasUsage={summary.hasUsage}
          >
            <div className="space-y-5">
              <UsageSummaryTiles summary={summary} metric={metric} windowDays={windowDays} />
              <UsageOverviewChart
                chart={chart}
                labelOf={labelOf}
                density="comfortable"
                scale={scale}
                metric={metric}
                windowDays={windowDays}
                emptyText={emptyUsageRange(t, metric)}
              />
            </div>
          </StatsBody>
        </SettingsSubsection>
      </SettingsGroup>
    </SettingsPageSection>
  );
}

export function StatsBody({
  windowDays,
  isLoading,
  error,
  hasUsage,
  children,
}: {
  /** Sizes the loading placeholder like the chart of the selected range. */
  windowDays: number;
  isLoading: boolean;
  error: unknown;
  hasUsage: boolean;
  children: React.ReactNode;
}): React.JSX.Element {
  const { t } = useUiTranslation();
  if (error && !hasUsage) {
    return (
      <p className="rounded-lg border border-[color-mix(in_oklab,var(--acc-red)_35%,transparent)] bg-[color-mix(in_oklab,var(--acc-red)_5%,var(--card))] px-3 py-2.5 text-xs text-foreground">
        {t("system.usage.loadError", "Could not load usage stats.")}{" "}
        {apiErrorMessage(error, t("system.usage.tryAgain", "Please try again."))}
      </p>
    );
  }
  if (isLoading && !hasUsage) {
    return (
      <div
        className="space-y-5"
        aria-busy="true"
        aria-label={t("system.statsSection.loadingUsageStats", "Loading usage stats")}
      >
        <div className="grid grid-cols-2 gap-2 lg:grid-cols-4">
          {Array.from({ length: 4 }, (_, index) => (
            <Skeleton key={index} className="h-[62px] rounded-lg" />
          ))}
        </div>
        <UsagePlotSkeleton days={windowDays} density="comfortable" />
      </div>
    );
  }
  if (!hasUsage) {
    return (
      <p className="rounded-lg border border-dashed border-border/60 px-3 py-6 text-center text-xs text-muted-foreground">
        {t(
          "system.statsSection.noUsageRecordedYetSendAPrompt",
          "No usage recorded yet. Send a prompt to an agent and it will show up here.",
        )}
      </p>
    );
  }
  if (!error) return <>{children}</>;
  return (
    <div className="space-y-4">
      <p role="status" className={cn(WARNING_BANNER_CLASS, "text-xs text-foreground")}>
        {t(
          "system.usage.refreshError",
          "Could not refresh usage stats. Showing the last loaded data.",
        )}{" "}
        {apiErrorMessage(error, t("system.usage.tryAgain", "Please try again."))}
      </p>
      {children}
    </div>
  );
}
